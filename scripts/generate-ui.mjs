#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const UI_DIR = path.join(ROOT, 'ui');
const UI_ENTRY = path.join(ROOT, 'ui.js');

const PARTS = [
  '01-foundation.js',
  '02-lifecycle.js',
  '03-gameplay.js',
  '04-growth-actions.js',
  '05-rendering.js'
];

function assemble() {
  const body = PARTS.map((name) => {
    const filePath = path.join(UI_DIR, name);
    return `/* ===== ui/${name} ===== */\n${fs.readFileSync(filePath, 'utf8').trim()}\n`;
  }).join('\n');
  const header = '/* Generated by scripts/generate-ui.mjs. Edit the sources in ui/. */';
  fs.writeFileSync(UI_ENTRY, `${header}\n\n${body.trimEnd()}\n`, 'utf8');
  console.log(`ui.js assembled from ${PARTS.length} source modules.`);
}

assemble();
